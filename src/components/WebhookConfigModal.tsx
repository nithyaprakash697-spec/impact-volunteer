import React, { useState, useEffect } from 'react';
import { useApp } from '../context/AppContext';
import {
  X,
  CheckCircle2,
  Copy,
  Check,
  Server,
  Zap,
  ShieldCheck,
  Info,
  Clock,
  Link,
} from 'lucide-react';
import { getWebhookConfig, saveWebhookConfig } from '../services/webhookService';

export const WebhookConfigModal: React.FC = () => {
  const { isWebhookModalOpen, setIsWebhookModalOpen, runId, approveUrl } = useApp();
  const [profileUrl, setProfileUrl] = useState('');
  const [resultUrl, setResultUrl] = useState('');
  const [useProxy, setUseProxy] = useState(true);
  const [simulationMode, setSimulationMode] = useState(false);
  const [savedSuccess, setSavedSuccess] = useState(false);
  const [copiedSection, setCopiedSection] = useState<string | null>(null);

  useEffect(() => {
    if (isWebhookModalOpen) {
      const config = getWebhookConfig();
      setProfileUrl(config.customProfileUrl || config.envProfileUrl || '');
      setResultUrl(config.customResultUrl || config.envResultUrl || config.registrationResultUrl || '');
      setUseProxy(config.useProxy);
      setSimulationMode(config.simulationMode);
      setSavedSuccess(false);
    }
  }, [isWebhookModalOpen]);

  if (!isWebhookModalOpen) return null;

  const handleSave = (e: React.FormEvent) => {
    e.preventDefault();
    saveWebhookConfig({
      customProfileUrl: profileUrl.trim(),
      customResultUrl: resultUrl.trim(),
      useProxy,
      simulationMode,
    });
    setSavedSuccess(true);
    setTimeout(() => {
      setSavedSuccess(false);
      setIsWebhookModalOpen(false);
    }, 1000);
  };

  const copyToClipboard = (text: string, id: string) => {
    navigator.clipboard.writeText(text);
    setCopiedSection(id);
    setTimeout(() => setCopiedSection(null), 2000);
  };

  const sampleProfilePayload = JSON.stringify(
    {
      name: "Student Name",
      cause: "Environment",
      skills: ["Communication", "Teaching", "Basic Computer Skills"],
      availability: "Weekends",
      age: 17,
      background_consent: false,
      city: "Coimbatore, India",
      workmode: "Remote"
    },
    null,
    2
  );

  const sampleApprovalPayload = JSON.stringify(
    {
      selected_ids: ["IND-TN-261108-104"],
      background_check_consent: false,
      unverified_requirements_ack: false
    },
    null,
    2
  );

  const sampleFinalResultPayload = JSON.stringify(
    {
      run_id: "run_example_123",
      student: {
        id: "stu_example_004",
        name: "Nithya Prakash"
      },
      outcome: "registered",
      registered: [
        {
          opportunity_id: "IND-TN-261108-104",
          title: "Community Health Outreach Volunteer",
          status: "registered_sandbox",
          confirmation_id: "SBX-EXAMPLE123"
        }
      ],
      not_registered: [
        {
          opportunity_id: "IND-KL-261114-315",
          title: "Example Community Volunteer Event",
          status: "waitlisted",
          reason: "Opportunity is full"
        },
        {
          opportunity_id: "IND-TN-261108-200",
          title: "Example Duplicate Opportunity",
          status: "already_registered",
          reason: "Already registered for this opportunity"
        },
        {
          opportunity_id: "IND-TN-261108-300",
          title: "Example Unselected Opportunity",
          status: "rejected_by_student",
          reason: "The student did not select this opportunity"
        }
      ],
      summary_html: "Registration summary generated by the n8n workflow."
    },
    null,
    2
  );

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-labelledby="webhook-modal-title"
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fade-in"
    >
      <div className="relative w-full max-w-2xl bg-[#0B211A] border border-[rgba(198,255,94,0.2)] rounded-2xl shadow-2xl overflow-hidden max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="px-6 py-5 border-b border-[rgba(198,255,94,0.12)] flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="p-2 bg-[#10251D] border border-[rgba(198,255,94,0.2)] rounded-lg text-[#C6FF5E]">
              <Server className="w-5 h-5" />
            </div>
            <div>
              <h2 id="webhook-modal-title" className="text-base font-display font-bold text-[#F5F4EC]">
                n8n Webhook Architecture
              </h2>
              <p className="text-xs text-[#A7B7A9]">
                Configured entrypoint and dynamic Wait node execution resume links
              </p>
            </div>
          </div>
          <button
            onClick={() => setIsWebhookModalOpen(false)}
            className="p-1.5 text-[#A7B7A9] hover:text-[#F5F4EC] rounded-lg transition-colors cursor-pointer"
            aria-label="Close modal"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        <div className="px-6 py-5 overflow-y-auto space-y-6 text-sm">
          <form onSubmit={handleSave} className="space-y-5">
            {/* Field: Profile Webhook URL */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-[#F5F4EC]">
                  Profile Matching Entrypoint Webhook URL
                </label>
                <span className="text-[11px] text-[#A7B7A9]">
                  Env: <code className="font-mono text-[#C6FF5E]">VITE_PROFILE_MATCH_WEBHOOK_URL</code>
                </span>
              </div>
              <input
                type="url"
                value={profileUrl}
                onChange={(e) => setProfileUrl(e.target.value)}
                placeholder="https://your-n8n-instance.com/webhook/student-profile-match"
                className="w-full px-3.5 py-2.5 bg-[#071C16] border border-[rgba(198,255,94,0.2)] rounded-lg text-[#F5F4EC] text-xs font-mono placeholder:text-[#A7B7A9]/40 focus:outline-none focus:border-[#C6FF5E] focus:ring-1 focus:ring-[#C6FF5E]"
              />
              <p className="text-[11px] text-[#A7B7A9]">
                Triggered on student profile submission. Expects the 8 exact student fields and returns <code>run_id</code>, <code>student</code>, <code>matches</code>, and <code>approve_url</code>.
              </p>
            </div>

            {/* Field: Registration Result Webhook URL */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-[#F5F4EC]">
                  Registration Result Webhook URL (Data Table Reader)
                </label>
                <span className="text-[11px] text-[#A7B7A9]">
                  Env: <code className="font-mono text-[#C6FF5E]">VITE_REGISTRATION_RESULT_WEBHOOK_URL</code>
                </span>
              </div>
              <input
                type="url"
                value={resultUrl}
                onChange={(e) => setResultUrl(e.target.value)}
                placeholder="https://your-n8n-instance.com/webhook/registration-result"
                className="w-full px-3.5 py-2.5 bg-[#071C16] border border-[rgba(198,255,94,0.2)] rounded-lg text-[#F5F4EC] text-xs font-mono placeholder:text-[#A7B7A9]/40 focus:outline-none focus:border-[#C6FF5E] focus:ring-1 focus:ring-[#C6FF5E]"
              />
              <p className="text-[11px] text-[#A7B7A9]">
                Optional. Used only if your approval Wait node returns an intermediate response and relies on a separate reader webhook to fetch Data Table records. If your workflow returns final registration results directly from the approval resume call, this is handled automatically.
              </p>
            </div>

            {/* Dynamic Approval URL Information Panel */}
            <div className="p-4 bg-[#071C16] border border-[rgba(198,255,94,0.18)] rounded-xl space-y-2.5">
              <div className="flex items-center gap-2">
                <Link className="w-4 h-4 text-[#C6FF5E]" />
                <span className="text-xs font-semibold text-[#F5F4EC]">
                  Approval Resume URL (Dynamic · Generated by n8n Wait Node)
                </span>
              </div>
              <p className="text-xs text-[#A7B7A9] leading-relaxed">
                Approval URLs are temporary, execution-specific resume webhooks generated dynamically by your n8n workflow for each student search. They are saved in application state per session and are never manually copied, hardcoded, or permanently stored.
              </p>
              <div className="pt-1 grid grid-cols-1 sm:grid-cols-2 gap-2 text-[11px] font-mono">
                <div className="p-2 bg-[#10251D] rounded-lg text-[#A7B7A9]">
                  Current Run ID: <strong className="text-[#F5F4EC]">{runId || 'None'}</strong>
                </div>
                <div className="p-2 bg-[#10251D] rounded-lg text-[#A7B7A9]">
                  Resume Link Status:{' '}
                  <strong className={approveUrl ? 'text-[#C6FF5E]' : 'text-[#A7B7A9]'}>
                    {approveUrl ? 'Active In Session' : 'None in memory'}
                  </strong>
                </div>
              </div>
            </div>

            {/* Proxy & CORS Control */}
            <div className="p-3.5 bg-[#071C16] border border-[rgba(198,255,94,0.15)] rounded-xl space-y-2">
              <div className="flex items-start justify-between gap-4">
                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <ShieldCheck className="w-4 h-4 text-[#C6FF5E]" />
                    <span className="text-xs font-semibold text-[#F5F4EC]">
                      Express Server Proxy (CORS Bypass)
                    </span>
                  </div>
                  <p className="text-[11px] text-[#A7B7A9] leading-relaxed">
                    Routes webhook calls through our server endpoint (<code>/api/proxy</code>) to prevent browser cross-origin (CORS) blocks when connecting to external n8n instances.
                  </p>
                </div>
                <input
                  type="checkbox"
                  id="proxyToggle"
                  checked={useProxy}
                  onChange={(e) => setUseProxy(e.target.checked)}
                  className="mt-1 h-4 w-4 accent-[#C6FF5E] rounded cursor-pointer"
                />
              </div>
            </div>

            {/* Test Simulator Mode */}
            <div className="p-3.5 bg-[#10251D] border border-[rgba(198,255,94,0.15)] rounded-xl space-y-2">
              <div className="flex items-start justify-between gap-4">
                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <Zap className="w-4 h-4 text-[#C6FF5E]" />
                    <span className="text-xs font-semibold text-[#F5F4EC]">
                      Interactive Test Simulator Mode
                    </span>
                  </div>
                  <p className="text-[11px] text-[#A7B7A9] leading-relaxed">
                    Provides schema-compliant sample responses (including simulated <code>run_id</code>, <code>matches</code>, and <code>approve_url</code>) for UI testing when n8n is offline.
                  </p>
                </div>
                <input
                  type="checkbox"
                  id="simToggle"
                  checked={simulationMode}
                  onChange={(e) => setSimulationMode(e.target.checked)}
                  className="mt-1 h-4 w-4 accent-[#C6FF5E] rounded cursor-pointer"
                />
              </div>
            </div>

            {/* Action buttons */}
            <div className="pt-2 flex items-center justify-end gap-3">
              <button
                type="button"
                onClick={() => setIsWebhookModalOpen(false)}
                className="px-4 py-2 text-xs font-medium text-[#A7B7A9] hover:text-[#F5F4EC] transition-colors cursor-pointer"
              >
                Cancel
              </button>
              <button
                type="submit"
                className="px-5 py-2 text-xs font-semibold text-[#14251B] bg-[#C6FF5E] hover:bg-[#d6ff85] active:scale-95 rounded-lg transition-all flex items-center gap-2 cursor-pointer shadow-sm"
              >
                {savedSuccess ? (
                  <>
                    <CheckCircle2 className="w-4 h-4 text-[#14251B]" />
                    Saved!
                  </>
                ) : (
                  'Save Settings'
                )}
              </button>
            </div>
          </form>

          {/* n8n Payload Specification */}
          <div className="pt-4 border-t border-[rgba(198,255,94,0.1)] space-y-4">
            <div className="flex items-center gap-2 text-xs font-semibold text-[#F5F4EC]">
              <Info className="w-4 h-4 text-[#C6FF5E]" />
              <span>n8n Payload Contracts</span>
            </div>

            {/* Profile Request Schema */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between text-[11px] text-[#A7B7A9]">
                <span>1. Profile Match Request (POST to Profile Webhook)</span>
                <button
                  type="button"
                  onClick={() => copyToClipboard(sampleProfilePayload, 'profile')}
                  className="flex items-center gap-1 hover:text-[#C6FF5E] transition-colors cursor-pointer"
                >
                  {copiedSection === 'profile' ? <Check className="w-3 h-3 text-[#C6FF5E]" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedSection === 'profile' ? 'Copied' : 'Copy JSON'}</span>
                </button>
              </div>
              <pre className="p-3 bg-[#071C16] border border-[rgba(198,255,94,0.1)] rounded-lg text-[11px] font-mono text-[#A7B7A9] overflow-x-auto">
                {sampleProfilePayload}
              </pre>
            </div>

            {/* Approval Request Schema */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between text-[11px] text-[#A7B7A9]">
                <span>2. Approval Request (POST to dynamic approve_url)</span>
                <button
                  type="button"
                  onClick={() => copyToClipboard(sampleApprovalPayload, 'approval')}
                  className="flex items-center gap-1 hover:text-[#C6FF5E] transition-colors cursor-pointer"
                >
                  {copiedSection === 'approval' ? <Check className="w-3 h-3 text-[#C6FF5E]" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedSection === 'approval' ? 'Copied' : 'Copy JSON'}</span>
                </button>
              </div>
              <pre className="p-3 bg-[#071C16] border border-[rgba(198,255,94,0.1)] rounded-lg text-[11px] font-mono text-[#A7B7A9] overflow-x-auto">
                {sampleApprovalPayload}
              </pre>
            </div>

            {/* Final Registration Result Schema */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between text-[11px] text-[#A7B7A9]">
                <span>3. Final Registration Result (from Data Table / registration-result)</span>
                <button
                  type="button"
                  onClick={() => copyToClipboard(sampleFinalResultPayload, 'final_result')}
                  className="flex items-center gap-1 hover:text-[#C6FF5E] transition-colors cursor-pointer"
                >
                  {copiedSection === 'final_result' ? <Check className="w-3 h-3 text-[#C6FF5E]" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedSection === 'final_result' ? 'Copied' : 'Copy JSON'}</span>
                </button>
              </div>
              <pre className="p-3 bg-[#071C16] border border-[rgba(198,255,94,0.1)] rounded-lg text-[11px] font-mono text-[#A7B7A9] overflow-x-auto max-h-56">
                {sampleFinalResultPayload}
              </pre>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
